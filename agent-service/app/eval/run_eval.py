"""Run the evaluation and write eval/results.md.

Two things are measured:

1. Citation verification. For every hand-labeled (claim, chunk, label) example
   we compute the embedding similarity and the five features, then score two
   verifiers against the labels:
     * baseline   — the similarity threshold used at runtime
     * classifier — logistic regression, scored with 5-fold cross-validation so
                    we never test on data we trained on
   We report accuracy / precision / recall / F1 for each, and save the
   classifier trained on all the data so the running app uses it.

2. Cannot-answer (anti-hallucination). With --live, each question in the
   cannot-answer set is run through the real pipeline for a given user; the
   system must refuse every one. We report the false-answer rate.

Usage (inside the agent container):
    python -m app.eval.run_eval --labeled eval/labeled_set.json \
        --cannot-answer eval/cannot_answer_set.json --out eval/results.md
    # add --live --user-id <uuid> to also run the cannot-answer set
"""
from __future__ import annotations

import argparse
import json

import numpy as np
from sklearn.model_selection import StratifiedKFold, cross_val_predict

from app.config import settings
from app.eval import baseline, classifier
from app.eval.features import extract_features
from app.eval.metrics import Scores, score


def _load(path: str) -> list[dict]:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def evaluate_citations(labeled: list[dict]) -> tuple[Scores, Scores, dict]:
    from app.ingestion.embeddings import cosine, embed_texts

    claims = [ex["claim"] for ex in labeled]
    chunks = [ex["cited_chunk"] for ex in labeled]
    y = np.array([baseline.label_to_int(ex["label"]) for ex in labeled])

    claim_vecs = embed_texts(claims)
    chunk_vecs = embed_texts(chunks)

    sims = np.array([cosine(claim_vecs[i], chunk_vecs[i]) for i in range(len(labeled))])
    feats = np.array(
        [extract_features(claims[i], chunks[i], sims[i]) for i in range(len(labeled))],
        dtype=np.float32,
    )

    # --- baseline: fixed similarity threshold (same as runtime) ---
    base_pred = [baseline.predict(s, settings.citation_support_threshold) for s in sims]
    base_scores = score(list(y), base_pred)

    # --- classifier: honest cross-validated predictions ---
    min_class = int(min(np.bincount(y))) if len(y) else 0
    if min_class >= 2:
        folds = min(5, min_class)
        skf = StratifiedKFold(n_splits=folds, shuffle=True, random_state=42)
        cv_pred = cross_val_predict(classifier.new_model(), feats, y, cv=skf)
        clf_scores = score(list(y), list(cv_pred))
        cv_note = f"{folds}-fold cross-validation"
    else:
        model = classifier.train(feats, y)
        clf_scores = score(list(y), list(model.predict(feats)))
        cv_note = "trained==tested (too few examples for cross-validation)"

    # Train on everything and save so the live app uses the classifier.
    final_model = classifier.train(feats, y)
    classifier.save(final_model, settings.classifier_path)

    meta = {"count": len(labeled), "positives": int(y.sum()), "cv_note": cv_note}
    return base_scores, clf_scores, meta


def evaluate_cannot_answer(questions: list[dict], user_id: str) -> dict:
    from app.graph import pipeline

    total = len(questions)
    wrong = []
    for q in questions:
        result = pipeline.run(user_id, q["question"], None)
        if result["answered"]:
            wrong.append(q["question"])
    refused = total - len(wrong)
    return {
        "total": total,
        "refused": refused,
        "false_answers": len(wrong),
        "false_answer_rate": (len(wrong) / total) if total else 0.0,
        "wrong": wrong,
    }


def write_results(path: str, base: Scores, clf: Scores, meta: dict, na: dict | None) -> None:
    lines = [
        "# Evaluation results",
        "",
        "_Generated by `python -m app.eval.run_eval` (`make eval`)._",
        "",
        "## Citation verification",
        "",
        f"- Labeled examples: **{meta['count']}** "
        f"({meta['positives']} supports, {meta['count'] - meta['positives']} does-not-support)",
        f"- Classifier scored with {meta['cv_note']}.",
        "",
        "| Method | Accuracy | Precision | Recall | F1 |",
        "|---|---|---|---|---|",
        f"| Baseline (similarity ≥ {settings.citation_support_threshold}) | {base.as_row()} |",
        f"| Classifier (logistic regression) | {clf.as_row()} |",
        "",
        "## Cannot-answer (anti-hallucination) check",
        "",
    ]
    if na is None:
        lines += [
            "_Not run in this pass. Run with `--live --user-id <uuid>` against a "
            "user who has papers uploaded to measure the false-answer rate._",
        ]
    else:
        lines += [
            f"- Questions the papers cannot answer: **{na['total']}**",
            f"- Correctly refused: **{na['refused']}**",
            f"- **False-answer rate: {na['false_answer_rate']:.1%}**",
        ]
        if na["wrong"]:
            lines.append("")
            lines.append("Questions that were (incorrectly) answered:")
            lines += [f"- {q}" for q in na["wrong"]]
    lines.append("")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--labeled", default="eval/labeled_set.json")
    ap.add_argument("--cannot-answer", default="eval/cannot_answer_set.json")
    ap.add_argument("--out", default="eval/results.md")
    ap.add_argument("--live", action="store_true", help="also run the cannot-answer set")
    ap.add_argument("--user-id", default="", help="user whose papers to test against (with --live)")
    args = ap.parse_args()

    labeled = _load(args.labeled)
    base, clf, meta = evaluate_citations(labeled)
    print(f"baseline : {base.as_row()}")
    print(f"classifier: {clf.as_row()}")

    na = None
    if args.live and args.user_id:
        na = evaluate_cannot_answer(_load(args.cannot_answer), args.user_id)
        print(f"cannot-answer false-answer rate: {na['false_answer_rate']:.1%}")

    write_results(args.out, base, clf, meta, na)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
